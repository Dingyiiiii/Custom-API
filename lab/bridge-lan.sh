#!/bin/sh
#
# Convert a NetworkManager-managed physical interface into a Linux bridge so
# that libvirt guests can attach to the real LAN instead of a NAT network.
#
# Why a bridge and not macvtap
#
# libvirt's macvtap passthrough gives a guest a LAN address without touching the
# host's configuration, but macvtap in bridge mode cannot exchange traffic with
# its *own* host. That would leave the libvirt host unable to reach the guest it
# runs - the opposite of what is wanted when the host is the management station.
# A Linux bridge has no such limitation.
#
# Safety
#
# Replacing the host's primary interface is the kind of change that ends a
# remote session if it goes wrong, so this script is built to fail open:
#
#   * the original connection profile is cloned and kept, not deleted;
#   * the physical interface's MAC is moved onto the bridge, so the existing
#     DHCP lease (often effectively permanent) is reused rather than requested
#     anew;
#   * an ARM TIMER is started before anything is changed. If the host does not
#     confirm success within TIMEOUT seconds, the timer automatically reverts
#     the configuration and restores connectivity.
#
# The caller confirms success by running:
#
#     <this script> --confirm
#
# which cancels the pending rollback.
#
# Usage:
#   ./bridge-lan.sh --iface eno1 --bridge br-lan [--timeout 120]
#   ./bridge-lan.sh --confirm
#   ./bridge-lan.sh --rollback
#   ./bridge-lan.sh --status

set -eu

IFACE=eno1
BRIDGE=br-lan
TIMEOUT=120
ACTION=setup
UNIT=lab-bridge-rollback
SELF=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)/$(basename -- "$0")

log() { printf '\033[1m==>\033[0m %s\n' "$*"; }
die() { printf '\033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }
nsudo() { sudo -n "$@"; }

while [ $# -gt 0 ]; do
	case "$1" in
	--iface) IFACE="$2"; shift 2 ;;
	--bridge) BRIDGE="$2"; shift 2 ;;
	--timeout) TIMEOUT="$2"; shift 2 ;;
	--confirm) ACTION=confirm; shift ;;
	--rollback) ACTION=rollback; shift ;;
	--status) ACTION=status; shift ;;
	-h|--help) sed -n '2,40p' "$0"; exit 0 ;;
	*) die "unknown option: $1" ;;
	esac
done

# ---------------------------------------------------------------------------
# rollback machinery
# ---------------------------------------------------------------------------

install_rollback() {
	sudo -n tee /usr/local/sbin/lab-bridge-rollback >/dev/null <<EOF
#!/bin/sh
# Generated by bridge-lan.sh. Reverts ${BRIDGE} back to a plain ${IFACE}
# connection. Invoked automatically by ${UNIT}.service if the change is not
# confirmed, and on demand with: ${SELF} --rollback
set -eu
nmcli connection down ${BRIDGE} 2>/dev/null || true
nmcli connection delete ${BRIDGE} 2>/dev/null || true
nmcli connection up ${IFACE} 2>/dev/null || true
nmcli connection delete ${IFACE}-slave 2>/dev/null || true
echo "lab-bridge-rollback: reverted to ${IFACE}"
EOF
	sudo -n chmod 0755 /usr/local/sbin/lab-bridge-rollback

	sudo -n tee /etc/systemd/system/${UNIT}.service >/dev/null <<EOF
[Unit]
Description=Roll back the ${BRIDGE} bridge on ${IFACE} unless confirmed
After=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/lab-bridge-rollback
EOF

	sudo -n tee /etc/systemd/system/${UNIT}.timer >/dev/null <<EOF
[Unit]
Description=Deadline for confirming the ${BRIDGE} bridge on ${IFACE}

[Timer]
OnActiveSec=${TIMEOUT}
AccuracySec=1s
Unit=${UNIT}.service

[Install]
WantedBy=timers.target
EOF

	sudo -n systemctl daemon-reload
	sudo -n systemctl start ${UNIT}.timer
	log "armed automatic rollback in ${TIMEOUT}s (confirm with: $0 --confirm)"
}

cancel_rollback() {
	sudo -n systemctl stop ${UNIT}.timer 2>/dev/null || true
	sudo -n systemctl stop ${UNIT}.service 2>/dev/null || true
	log "automatic rollback cancelled"
}

do_rollback() {
	cancel_rollback
	log "rolling back manually"
	sudo -n /usr/local/sbin/lab-bridge-rollback || die "rollback script failed"
	sudo -n systemctl disable ${UNIT}.timer 2>/dev/null || true
}

# ---------------------------------------------------------------------------

show_status() {
	echo "--- connections"
	nmcli -t -f NAME,DEVICE,TYPE,STATE connection show 2>/dev/null | head -10
	echo "--- links"
	ip -br addr | head -8
	echo "--- bridge members"
	for b in $(ls /sys/class/net 2>/dev/null); do
		if [ -d "/sys/class/net/$b/bridge" ]; then
			echo "  $b: $(ls /sys/class/net/$b/brif 2>/dev/null | tr '\n' ' ')"
		fi
	done
	echo "--- rollback timer"
	sudo -n systemctl is-active ${UNIT}.timer 2>/dev/null || echo "  (inactive)"
}

setup_bridge() {
	[ "$(id -u)" = "0" ] || nsudo true 2>/dev/null || die "root or passwordless sudo required"
	command -v nmcli >/dev/null 2>&1 || die "NetworkManager (nmcli) is required"

	ip link show "${IFACE}" >/dev/null 2>&1 || die "interface ${IFACE} does not exist"

	# Find the connection profile that owns the interface, falling back to the
	# conventional same-name profile.
	CONN=$(nmcli -t -f NAME,DEVICE connection show --active 2>/dev/null \
		| awk -F: -v d="${IFACE}" '$2==d{print $1; exit}')
	[ -n "${CONN}" ] || CONN=$(nmcli -t -f NAME,DEVICE connection show 2>/dev/null \
		| awk -F: -v d="${IFACE}" '$2==d{print $1; exit}')
	[ -n "${CONN}" ] || CONN="${IFACE}"

	HWADDR=$(cat "/sys/class/net/${IFACE}/address")
	MTU=$(cat "/sys/class/net/${IFACE}/mtu" 2>/dev/null || echo 1500)

	log "interface   : ${IFACE} (connection '${CONN}', MAC ${HWADDR}, MTU ${MTU})"
	log "bridge      : ${BRIDGE}"

	if nmcli -t -f NAME connection show 2>/dev/null | grep -qx "${BRIDGE}"; then
		log "a '${BRIDGE}' connection already exists; nothing to do"
		show_status
		return 0
	fi

	install_rollback

	# 1. Create the bridge and give it the physical interface's identity so the
	#    existing DHCP lease continues to apply.
	log "step 1/3: creating ${BRIDGE}"
	nsudo nmcli connection add type bridge ifname "${BRIDGE}" con-name "${BRIDGE}" \
		connection.autoconnect yes \
		bridge.stp no \
		bridge.mac-address "${HWADDR}" \
		ipv4.method auto ipv6.method ignore \
		> /dev/null

	# 2. Attach the physical interface as a bridge port.
	log "step 2/3: enslaving ${IFACE}"
	nsudo nmcli connection add type ethernet ifname "${IFACE}" con-name "${IFACE}-slave" \
		connection.autoconnect yes \
		connection.master "${BRIDGE}" connection.slave-type bridge \
		> /dev/null

	# 3. Activate the bridge, then its port.
	#
	# The order matters and is counter-intuitive: a bridge with no port has no
	# carrier, so activating it alone leaves it in NetworkManager's "config"
	# state waiting forever for a carrier that only the port can provide.
	# Activating the slave immediately after gives the bridge its carrier and
	# lets the DHCP request proceed. Both commands are needed - `nmcli
	# connection add` marks the profiles autoconnect but does not activate the
	# bridge, and the port activation alone would leave the bridge unconfigured.
	log "step 3/3: activating ${BRIDGE} and its port"
	nsudo nmcli connection up "${BRIDGE}" > /dev/null 2>&1 || true
	nsudo nmcli connection up "${IFACE}-slave" > /dev/null 2>&1 || true

	# NetworkManager applies addresses asynchronously.
	for _ in $(seq 1 30); do
		if ip -4 addr show "${BRIDGE}" 2>/dev/null | grep -q "inet "; then
			break
		fi
		sleep 1
	done

	echo
	show_status
	echo
	ADDR=$(ip -4 -br addr show "${BRIDGE}" 2>/dev/null | awk '{print $3}')
	if [ -n "${ADDR}" ]; then
		log "${BRIDGE} is up with ${ADDR}"
	else
		log "WARNING: ${BRIDGE} has no IPv4 address yet"
	fi
	echo
	log "NEXT: verify connectivity, then run: $0 --confirm"
	log "      if connectivity is lost, the rollback fires automatically in ${TIMEOUT}s"
}

case "${ACTION}" in
setup)    setup_bridge ;;
confirm)
	cancel_rollback
	# Disable as well as stop: the timer is a one-shot deadline, not a service
	# that should come back after a reboot.
	nsudo systemctl disable ${UNIT}.timer 2>/dev/null || true
	show_status
	;;
rollback) do_rollback ;;
status)   show_status ;;
esac
